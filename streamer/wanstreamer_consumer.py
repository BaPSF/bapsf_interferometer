#!/usr/bin/env python3
"""Copy a native ADIOS2 WANStreamer input stream to rotating output files."""

import argparse
import sys
import time
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    __package__ = "streamer"

import adios2

from .consumer_output import (
    DEFAULT_FILE_INTERVAL_SECONDS,
    create_consumer_output,
    positive_float,
)
from .timing_log import TimingLog, timestamp


def parse_args(argv):
    parser = argparse.ArgumentParser(
        description="Read WANStreamer steps and commit them to ADIOS output."
    )
    parser.add_argument("connection_file", help="encrypted rendezvous file to create")
    parser.add_argument("output_directory", help="directory for timestamped outputs")
    parser.add_argument(
        "--public-key",
        required=True,
        help="Curve25519 public key generated by keygen.py",
    )
    parser.add_argument("--engine", default="BP5", help="output engine (default: BP5)")
    parser.add_argument(
        "--bind-host",
        default="0.0.0.0",
        help="interface on which WANStreamer listens (default: 0.0.0.0)",
    )
    parser.add_argument(
        "--advertise-host",
        default="127.0.0.1",
        help="host advertised to the producer (default: 127.0.0.1)",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=0,
        help="WANStreamer listening port; zero selects an available port",
    )
    parser.add_argument(
        "--checkpoint-file",
        help="persistent WANStreamer commit checkpoint",
    )
    parser.add_argument(
        "--timing-log",
        default="raw_output_consumer.log",
        help="timing log file (default: raw_output_consumer.log)",
    )
    parser.add_argument(
        "--file-interval-seconds",
        type=positive_float,
        default=DEFAULT_FILE_INTERVAL_SECONDS,
        help="seconds between new output files (default: 3600)",
    )
    return parser.parse_args(argv)


def read_variables(stream):
    return {
        name: stream.read(name)
        for name in stream.available_variables()
    }


def receive_steps(stream, output_directory, engine, timing_log, file_interval_seconds):
    output = None
    step = 0
    try:
        while True:
            receive_started_at = timestamp()
            receive_start = time.perf_counter()
            status = stream.begin_step()
            if status == adios2.StepStatus.EndOfStream:
                return
            if status != adios2.StepStatus.OK:
                continue
            variables = read_variables(stream)
            receive_fields = {
                "step": step,
                "variables": list(variables),
                "started_at": receive_started_at,
                "completed_at": timestamp(),
                "duration_seconds": time.perf_counter() - receive_start,
            }
            shot_index = None
            if "shot_index" in variables:
                shot_index = int(variables["shot_index"].reshape(-1)[0])
                receive_fields["shot"] = shot_index
            timing_log.record("wanstreamer.receive", **receive_fields)

            if output is None:
                output = create_consumer_output(
                    output_directory,
                    engine,
                    interval_seconds=file_interval_seconds,
                )

            write_start = time.perf_counter()
            try:
                # RotatingConsumerOutput -> AdiosIO.write_data() completes the
                # downstream BP5 EndStep before this call returns.
                output.write_data(variables)
            except Exception as exc:
                timing_log.record(
                    "io.write",
                    step=step,
                    status="error",
                    error_type=type(exc).__name__,
                    duration_seconds=time.perf_counter() - write_start,
                )
                # Deliberately do not acknowledge the WANStreamer step.
                raise
            timing_log.record(
                "io.write",
                step=step,
                status="ok",
                duration_seconds=time.perf_counter() - write_start,
            )
            stream.end_step()  # commit checkpoint and acknowledge the producer
            summary = ", ".join(
                f"{name}={value.shape}/{value.dtype}"
                for name, value in sorted(variables.items())
            )
            print(f"Received and committed step {step}: {summary}", flush=True)
            step += 1
    finally:
        if output is not None:
            output.close()


def main(argv=None):
    args = parse_args(sys.argv[1:] if argv is None else argv)
    timing_log = TimingLog(args.timing_log)
    adios = adios2.Adios()
    io = adios.declare_io("InterferometerWANInput")
    io.set_engine("WANStreamer")
    parameters = {
        "ConnectionFile": args.connection_file,
        "PublicKey": args.public_key,
        "BindAddress": args.bind_host,
        "AdvertiseAddress": args.advertise_host,
        "Port": str(args.port),
    }
    if args.checkpoint_file:
        parameters["CheckpointFile"] = args.checkpoint_file
    io.set_parameters(parameters)

    try:
        with adios2.Stream(io, "InterferometerRawOutput", "r") as stream:
            receive_steps(
                stream,
                args.output_directory,
                args.engine,
                timing_log,
                args.file_interval_seconds,
            )
    finally:
        timing_log.close()


if __name__ == "__main__":
    main()
